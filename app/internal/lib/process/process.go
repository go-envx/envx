package process

import (
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"os/signal"
	"sort"
	"syscall"

	"github.com/go-envx/envx/app/internal/lib/exitcode"
	"github.com/go-envx/envx/app/internal/lib/stdio"
	"github.com/go-envx/envx/app/internal/lib/terminal"
)

// ErrNoCommand is returned when command arguments are empty.
var ErrNoCommand = errors.New("no command specified")

// Command specifies a subprocess invocation, its injected environment,
// and its stream bundle.
type Command struct {
	Args    []string
	Env     map[string]string
	Streams stdio.Streams
}

// forwardedSignals are the signals Run watches and relays to the child process.
// Catching them keeps the supervisor process alive until the child terminates,
// enabling clean exit status mirroring.
var forwardedSignals = []os.Signal{
	os.Interrupt,    // SIGINT  — Ctrl+C
	syscall.SIGTERM, // supervisor stop signal
	syscall.SIGHUP,  // controlling terminal hangup
	syscall.SIGQUIT, // Ctrl+\
}

// ttyDeliveredSignals are generated by the terminal line discipline (Ctrl+C,
// Ctrl+\) and delivered to the whole foreground process group at once, so
// relaying them to an interactive child would double-deliver them.
var ttyDeliveredSignals = map[os.Signal]bool{
	os.Interrupt:    true, // SIGINT  — Ctrl+C
	syscall.SIGQUIT: true, // SIGQUIT — Ctrl+\
}

// Run executes the command with the complete specified environment and relays
// received signals until the child terminates.
//
// Streams are normalized on entry: omitted input yields EOF and omitted outputs
// are discarded without consulting process globals.
//
// A nil or empty environment produces an empty child environment rather than
// inheriting ambient process variables.
//
// Returned *exitcode.Error values preserve child status, signal-derived status,
// and conventional start failures (126 and 127).
func Run(command Command) error {
	if len(command.Args) == 0 {
		return ErrNoCommand
	}

	streams := command.Streams.Normalized()

	// exec.Command (not CommandContext) is deliberate: transparent process execution
	// forwards signals to the child and mirrors its exit status, so the child
	// owns its own shutdown. Binding it to a context would let cancellation
	// SIGKILL it out from under a graceful shutdown.
	//nolint:gosec,noctx // intentional; see comment above
	cmd := exec.Command(command.Args[0], command.Args[1:]...)
	cmd.Stdin = streams.In
	cmd.Stdout = streams.Out
	cmd.Stderr = streams.ErrOut
	cmd.Env = mapToEnv(command.Env)

	// Registered before Start so a signal arriving during startup cannot orphan the child.
	sigCh := make(chan os.Signal, 1)
	signal.Notify(sigCh, forwardedSignals...)
	defer signal.Stop(sigCh)

	if err := cmd.Start(); err != nil {
		return exitcode.New(startFailureCode(err), err)
	}

	interactive := stdinIsTerminal(streams.In)

	waitDone := make(chan struct{})
	go func() {
		for {
			select {
			case sig := <-sigCh:
				if shouldForward(sig, interactive) {
					_ = cmd.Process.Signal(sig)
				}
			case <-waitDone:
				return
			}
		}
	}()

	err := cmd.Wait()
	close(waitDone)

	if err == nil {
		return nil
	}
	if exitErr, ok := errors.AsType[*exec.ExitError](err); ok {
		return exitcode.FromCode(exitCode(exitErr))
	}
	return fmt.Errorf("running command: %w", err)
}

// shouldForward reports whether a received signal should be relayed to the
// child. Terminal-generated signals are skipped when attached to a tty because
// the tty already delivers them to the child's process group.
func shouldForward(sig os.Signal, interactive bool) bool {
	if interactive && ttyDeliveredSignals[sig] {
		return false
	}
	return true
}

// stdinIsTerminal reports whether standard input is an active terminal.
func stdinIsTerminal(stdin io.Reader) bool {
	if f, ok := stdin.(*os.File); ok {
		return terminal.IsTerminal(f)
	}
	return false
}

// mapToEnv converts a key-value map into KEY=VALUE slice entries suitable for
// exec.Cmd.Env. An empty or nil map returns a non-nil empty slice ([]string{})
// so os/exec does not fall back to inheriting the current process's environment.
func mapToEnv(m map[string]string) []string {
	if len(m) == 0 {
		return []string{}
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	result := make([]string, 0, len(m))
	for _, k := range keys {
		result = append(result, k+"="+m[k])
	}
	return result
}

// exitCode extracts the child's exit code, mapping a signal-terminated child to
// the shell convention 128+signum (e.g. 130 for SIGINT) instead of -1.
func exitCode(exitErr *exec.ExitError) int {
	if code := exitErr.ExitCode(); code >= 0 {
		return code
	}
	if ws, ok := exitErr.Sys().(syscall.WaitStatus); ok && ws.Signaled() {
		return 128 + int(ws.Signal())
	}
	return 1
}

// startFailureCode maps a failure to start the child to the shell's conventional
// exit code: 127 when the command was not found, and 126 when it could not be
// executed.
func startFailureCode(err error) int {
	if errors.Is(err, exec.ErrNotFound) || errors.Is(err, os.ErrNotExist) {
		return 127
	}
	return 126
}
